"""Discord OAuth2 (authorization-code flow) client.

See docs/data-model.md#authentication-and-entitlements — login is Discord
OAuth2 only, no local password storage. A `Person` row is upserted by
`discord_id` on every successful callback (see `app/auth/router.py`).
"""

from __future__ import annotations

import os

from authlib.integrations.httpx_client import AsyncOAuth2Client

DISCORD_CLIENT_ID = os.environ.get("DISCORD_CLIENT_ID", "")
DISCORD_CLIENT_SECRET = os.environ.get("DISCORD_CLIENT_SECRET", "")
DISCORD_REDIRECT_URI = os.environ.get(
    "DISCORD_REDIRECT_URI", "http://localhost:8000/auth/discord/callback"
)

DISCORD_AUTHORIZE_URL = "https://discord.com/oauth2/authorize"
DISCORD_TOKEN_URL = "https://discord.com/api/oauth2/token"
DISCORD_USER_URL = "https://discord.com/api/users/@me"

# `identify` is enough to read id/username/avatar; we don't need the
# account's email or guild list for anything in this app.
DISCORD_SCOPE = "identify"


def build_authorize_url(state: str) -> str:
    """Build the Discord "Authorize" redirect URL for a login attempt.

    Args:
        state: Opaque CSRF token generated by the caller and mirrored in a
            short-lived cookie, so the callback can confirm the redirect back
            from Discord matches the request that started it.

    Returns:
        The full `https://discord.com/oauth2/authorize?...` URL to redirect
        the browser to.
    """
    client = AsyncOAuth2Client(
        DISCORD_CLIENT_ID, DISCORD_CLIENT_SECRET, redirect_uri=DISCORD_REDIRECT_URI, scope=DISCORD_SCOPE
    )
    uri, _ = client.create_authorization_url(DISCORD_AUTHORIZE_URL, state=state)
    return uri


async def fetch_discord_user(code: str) -> dict:
    """Exchange an authorization code for the Discord user it belongs to.

    Args:
        code: The `code` query parameter Discord appended to the callback
            redirect.

    Returns:
        The Discord user object (at minimum `id`, `username`, `avatar`) as
        returned by `GET /users/@me`.

    Raises:
        httpx.HTTPStatusError: If the token exchange or user-info request is
            rejected by Discord (e.g. an expired/reused code).
    """
    async with AsyncOAuth2Client(
        DISCORD_CLIENT_ID, DISCORD_CLIENT_SECRET, redirect_uri=DISCORD_REDIRECT_URI
    ) as client:
        await client.fetch_token(DISCORD_TOKEN_URL, code=code, grant_type="authorization_code")
        response = await client.get(DISCORD_USER_URL)
        response.raise_for_status()
        return response.json()


def discord_avatar_url(discord_user: dict) -> str | None:
    """Resolve a Discord user object's CDN avatar URL.

    Args:
        discord_user: The user object returned by `fetch_discord_user`.

    Returns:
        A CDN URL if the user has a custom avatar set, otherwise `None`
        (Discord users without one have no default-avatar CDN path worth
        persisting — the frontend can render a local fallback).
    """
    avatar_hash = discord_user.get("avatar")
    if not avatar_hash:
        return None
    return f"https://cdn.discordapp.com/avatars/{discord_user['id']}/{avatar_hash}.png"
